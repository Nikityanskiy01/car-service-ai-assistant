function norm(s) {
  return String(s || '').toLowerCase();
}

function dedupeLines(items) {
  const seen = new Set();
  const out = [];
  for (const raw of items || []) {
    const s = String(raw || '').trim();
    if (!s) continue;
    const key = s.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(s);
  }
  return out;
}

