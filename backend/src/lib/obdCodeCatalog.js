/**
 * @param {string[]} codes
 */
export function lookupObdCodes(codes) {
  return codes
    .map((code) => {
      const entry = OBD_CODE_CATALOG[code];
      if (!entry) {
        return { code, title: 'Код требует уточнения у мастера', plain: 'Расшифровка зависит от марки и года выпуска.', known: false };
      }
      return { code, ...entry, known: true };
    })
    .slice(0, 8);
}

/**
 * @param {string[]} codes
 */
export function formatObdForPrompt(codes) {
  const rows = lookupObdCodes(codes);
  if (!rows.length) return '';
  return rows.map((r) => `${r.code}: ${r.title} — ${r.plain}`).join('\n');
}
